// Generates ready-to-run SQL for Cloudflare D1 into deploy/:
//   deploy/seed.sql          base data: 37 states, Ogun LGAs, crops, default alert rules
//   deploy/demo-content.sql  flagged demo content (is_placeholder = 1), from content-templates/
// Run: npm run build:sql. Apply: npx wrangler d1 execute agrivoice --remote --file deploy/seed.sql
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { baseSeedStatements, lgaStatements, readTemplate, renderSql, stateCapitals, sqlLiteral, type Stmt } from '../apps/api/src/seed/index';

const root = join(import.meta.dirname, '..');
mkdirSync(join(root, 'deploy'), { recursive: true });

const lgas = (JSON.parse(readFileSync(join(root, 'scripts', 'data', 'lgas.json'), 'utf8')) as Record<string, string[]>)['Ogun']!;
const cap = stateCapitals().find((c) => c[0] === 'Ogun')!;
const seed = [...baseSeedStatements(), ...(await lgaStatements('Ogun', lgas, { lat: cap[2], lon: cap[3] }))];
writeFileSync(join(root, 'deploy', 'seed.sql'), '-- AgriVoice base data (generated by npm run build:sql). Safe to run more than once.\n' + renderSql(seed), 'utf8');

const nz = (v: string | undefined): string | number | null => (v === undefined || v === '' ? null : v);
const crop = (slug: string) => `(SELECT id FROM crops WHERE slug = ${sqlLiteral(slug)})`;
const out: string[] = ['-- AgriVoice DEMO content: every row is flagged is_placeholder = 1 and shown as "Demo data". Generated by npm run build:sql.', '-- Safe to run more than once: placeholder rows are replaced.'];
const del = ['price_reports', 'briefs', 'qa_items', 'alert_advice'].map((t) => `DELETE FROM ${t} WHERE is_placeholder = 1;`);
out.push(...del);

const lit = (v: string | number | null) => sqlLiteral(v);
const briefs = readTemplate('briefs.csv');
const slugs = readTemplate('crops.csv').map((c) => c.slug!);
// Same flagged placeholder wording for crops the template does not list, so every crop works end to end.
const base = briefs[0]!;
const briefRows = slugs.map((s) => briefs.find((b) => b.crop_slug === s) ?? { ...base, crop_slug: s });
for (const b of briefRows)
  out.push(
    `INSERT INTO briefs (state, crop_id, language, week_start, title, body, ussd_summary, audio_url, reviewer, approved_at, status, is_placeholder) VALUES (${[lit(b.state!), crop(b.crop_slug!), lit(b.language || 'en'), lit(b.week_start!), lit(b.title!), lit(b.body!), lit(nz(b.ussd_summary)), lit(nz(b.audio_url)), lit(nz(b.reviewer)), lit(nz(b.approved_at)), lit(b.status || 'approved')].join(', ')}, 1);`,
  );

const qa = readTemplate('qa.csv');
const crop0 = qa.find((q) => q.crop_slug) ?? qa[0]!;
const qaRows = [...slugs.map((s) => qa.find((q) => q.crop_slug === s) ?? { ...crop0, crop_slug: s }), ...qa.filter((q) => !q.crop_slug)];
for (const q of qaRows)
  out.push(
    `INSERT INTO qa_items (crop_id, language, question, answer, keywords, reviewer, approved_at, status, is_placeholder) VALUES (${[q.crop_slug ? crop(q.crop_slug) : 'NULL', lit(q.language || 'en'), lit(q.question!), lit(q.answer!), lit(q.keywords ?? ''), lit(nz(q.reviewer)), lit(nz(q.approved_at)), lit(q.status || 'approved')].join(', ')}, 1);`,
  );

const advice = readTemplate('alert_advice.csv');
for (const a of advice)
  out.push(
    `INSERT INTO alert_advice (rule_key, crop_id, language, text, reviewer, approved_at, status, is_placeholder) VALUES (${[lit(a.rule_key!), a.crop_slug ? crop(a.crop_slug) : 'NULL', lit(a.language || 'en'), lit(a.text!), lit(nz(a.reviewer)), lit(nz(a.approved_at)), lit(a.status || 'approved')].join(', ')}, 1);`,
  );

const markets = readTemplate('markets.csv');
for (const m of markets)
  out.push(
    `INSERT INTO markets (name, state, lga, lat, lon, is_placeholder) SELECT ${[lit(m.name!), lit(m.state!), lit(nz(m.lga)), lit(m.lat ? Number(m.lat) : null), lit(m.lon ? Number(m.lon) : null)].join(', ')}, 1 WHERE NOT EXISTS (SELECT 1 FROM markets WHERE name = ${lit(m.name!)} AND state = ${lit(m.state!)});`,
  );

// Placeholder prices (not real market data), approved so every screen has something to show.
let seq = 0;
for (const m of markets)
  for (const s of slugs) {
    seq++;
    out.push(
      `INSERT INTO price_reports (market_id, crop_id, unit, price_ngn, reported_at, status, reviewed_at, is_placeholder) VALUES ((SELECT id FROM markets WHERE name = ${lit(m.name!)} AND state = ${lit(m.state!)}), ${crop(s)}, 'bag', ${1000 * seq}, strftime('%Y-%m-%dT%H:%M:%fZ','now','-${seq} day'), 'approved', strftime('%Y-%m-%dT%H:%M:%fZ','now'), 1);`,
    );
  }
writeFileSync(join(root, 'deploy', 'demo-content.sql'), out.join('\n') + '\n', 'utf8');
void ({} as Stmt);
console.log(`deploy/seed.sql: ${seed.length} statements; deploy/demo-content.sql: ${out.length - 2} statements`);
